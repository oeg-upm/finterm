"""Immutable data passed between parsing, tree similarity and retrieval."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Iterable


LEXICAL_PLACEHOLDER = "__FASTKASSIM_LEAF__"


def require_text(value: str, name: str) -> None:
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{name} must be a nonempty string")


def identifier_set(values: Iterable[str], name: str) -> frozenset[str]:
    if isinstance(values, (str, bytes)):
        raise TypeError(f"{name} must be a collection of identifiers, not a string")
    result = frozenset(values)
    for value in result:
        require_text(value, name)
    return result


@dataclass(frozen=True, slots=True)
class SyntaxTree:
    """Constituent/POS labels only. A childless node is a POS preterminal.

    Word leaves are deliberately absent from this representation. They cannot
    reach a similarity implementation through the TreeSimilarity interface.
    """

    label: str
    children: tuple[SyntaxTree, ...] = ()

    def __post_init__(self) -> None:
        require_text(self.label, "tree label")
        if self.label == LEXICAL_PLACEHOLDER:
            raise ValueError("The lexical placeholder is not a constituent label")
        if any(char.isspace() or char in "()" for char in self.label):
            raise ValueError("A constituent/POS label cannot contain spaces or brackets")
        children = tuple(self.children)
        if not all(isinstance(child, SyntaxTree) for child in children):
            raise TypeError("SyntaxTree children must be SyntaxTree instances")
        object.__setattr__(self, "children", children)

    @classmethod
    def from_nltk(cls, tree: Any) -> SyntaxTree:
        """Discard lexical leaves from an already obtained constituency tree."""
        if isinstance(tree, str) or not callable(getattr(tree, "label", None)):
            raise TypeError("Expected a constituency tree with a label() method")
        children = tuple(tree)
        if not children:
            raise ValueError("An external constituency tree cannot have empty nodes")
        words = [isinstance(child, str) for child in children]
        if all(words):
            if len(children) != 1:
                raise ValueError("A POS preterminal must have exactly one word leaf")
            return cls(tree.label())
        if any(words):
            raise ValueError("Mixed word leaves and constituent children are unsupported")
        return cls(tree.label(), tuple(cls.from_nltk(child) for child in children))

    @classmethod
    def from_penn(cls, bracketed_tree: str) -> SyntaxTree:
        """Read predefined Penn brackets; this does not run a language parser."""
        from nltk.tree import Tree

        return cls.from_nltk(Tree.fromstring(bracketed_tree))

    def to_nltk(self) -> Any:
        """Restore the shape expected by upstream LTK, using constant leaves."""
        from nltk.tree import Tree

        children = (
            [child.to_nltk() for child in self.children]
            if self.children
            else [LEXICAL_PLACEHOLDER]
        )
        return Tree(self.label, children)


@dataclass(frozen=True, slots=True)
class ParsedText:
    """A forest with explicit parser identity; contains neither words nor terms."""

    trees: tuple[SyntaxTree, ...]
    parser_id: str

    def __post_init__(self) -> None:
        require_text(self.parser_id, "parser_id")
        trees = tuple(self.trees)
        if not trees or not all(isinstance(tree, SyntaxTree) for tree in trees):
            raise ValueError("ParsedText requires at least one SyntaxTree")
        object.__setattr__(self, "trees", trees)


@dataclass(frozen=True, slots=True)
class AnnotatedExample:
    """An existing annotation, never a prediction generated by this component."""

    identifier: str
    text: str
    terms: tuple[str, ...]
    document_id: str
    domain: str

    def __post_init__(self) -> None:
        for name in ("identifier", "text", "document_id", "domain"):
            require_text(getattr(self, name), name)
        if isinstance(self.terms, (str, bytes)):
            raise TypeError("terms must be a collection, not a single string")
        terms = tuple(self.terms)
        for term in terms:
            require_text(term, "term")
        # Preserve order, case, nesting and duplicate annotations as provided.
        object.__setattr__(self, "terms", terms)


@dataclass(frozen=True, slots=True)
class RetrievedExample:
    """A selected annotation and its syntactic score, ready for a later consumer."""

    example: AnnotatedExample
    score: float

    def to_dict(self) -> dict[str, Any]:
        """Return data only, without building any prompt or writing a file."""
        return {
            "id": self.example.identifier,
            "text": self.example.text,
            "terms": list(self.example.terms),
            "document_id": self.example.document_id,
            "domain": self.example.domain,
            "score": self.score,
        }
